    private fun buildSeasons(
        showId: String,
        showTitle: String,
        seasonCount: Int = 2,
        episodesPerSeason: Int = 4,
        accentHex: Long = 0xFFE50938
    ): List<SeasonItem> {
        val sampleStreams = listOf(
            "https://commondatastorage.googleapis.com/gtv-videos-bucket/sample/BigBuckBunny.mp4",
            "https://commondatastorage.googleapis.com/gtv-videos-bucket/sample/ElephantsDream.mp4",
            "https://commondatastorage.googleapis.com/gtv-videos-bucket/sample/ForBiggerBlazes.mp4",
            "https://commondatastorage.googleapis.com/gtv-videos-bucket/sample/Sintel.mp4"
        )
        return (1..seasonCount).map { sNum ->
            val eps = (1..episodesPerSeason).map { eNum ->
                EpisodeItem(
                    id = "${showId}_s${sNum}_e${eNum}",
                    showId = showId,
                    seasonNumber = sNum,
                    episodeNumber = eNum,
                    title = "Chapter $eNum: ${
                        when (eNum) {
                            1 -> "The Awakening Signal"
                            2 -> "Shadows Over the Strait"
                            3 -> "Echoes of the Velvet Throne"
                            else -> "Zero Hour Reckoning"
                        }
                    }",
                    description = "In Season $sNum Episode $eNum of $showTitle, alliances fracture as hidden transmissions expose the architect behind the global conspiracy.",
                    airDate = "2026-0${sNum}-1${eNum}",
                    runtimeMinutes = 46 + (eNum * 3),
                    rating = 8.4 + ((eNum % 3) * 0.3),
                    accentColorHex = accentHex,
                    streamUrl = sampleStreams[(sNum + eNum) % sampleStreams.size]
                )
            }
            SeasonItem(
                id = "${showId}_s$sNum",
                showId = showId,
                seasonNumber = sNum,
                title = "Season $sNum • ${if (sNum == 1) "Genesis Arc" else "Sovereign Protocol"}",
                overview = "Full official episodes for $showTitle Season $sNum with multi-language subtitles and adaptive 4K HLS delivery.",
                airDate = "202${4 + sNum}-03-10",
                episodes = eps
            )
        }
    }

